"""Templates turn module values into one program's config format (S02, S03, S04).

Built-in templates: bash, zsh and fish (from the `shellrc` module) and alacritty
(from the `theme` and `font` modules). A file `templates/<name>.tmpl` in the
config folder overrides the built-in template with the same name, or adds a new one.
Text templates use `{{ module.key }}` placeholders.
"""

import re
import shlex
from dataclasses import dataclass, replace
from pathlib import Path

from rosamta.errors import ConfigError
from rosamta.module import get_value

HEADER = "Generated by rosamta. Do not edit by hand."
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.-]+)\s*\}\}")

ALACRITTY = f"""# {HEADER}
[colors.primary]
background = "{{{{ theme.colors.background }}}}"
foreground = "{{{{ theme.colors.foreground }}}}"

[font]
size = {{{{ font.size }}}}

[font.normal]
family = "{{{{ font.family }}}}"
"""


def _home(path: str) -> str:
    return "$HOME/" + path[2:] if path.startswith("~/") else path


def _fish_quote(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _shell(kind: str, shellrc: dict) -> str:
    lines = [f"# {HEADER}"]
    env = shellrc.get("env", {})
    prepend = shellrc.get("path", {}).get("prepend", [])
    aliases = shellrc.get("alias", {})
    for name, value in env.items():
        if kind == "fish":
            lines.append(f"set -gx {name} {_fish_quote(str(value))}")
        else:
            lines.append(f"export {name}={shlex.quote(str(value))}")
    for folder in reversed(prepend):
        if kind == "fish":
            lines.append(f'set -gx PATH "{_home(folder)}" $PATH')
        else:
            lines.append(f'export PATH="{_home(folder)}:$PATH"')
    for name, command in aliases.items():
        if kind == "fish":
            lines.append(f"alias {name} {_fish_quote(str(command))}")
        else:
            lines.append(f"alias {name}={shlex.quote(str(command))}")
    return "\n".join(lines) + "\n"


@dataclass
class Template:
    name: str
    source: str           # "built-in" or the path of the user's file
    text: str | None      # text template, or None for code templates (shells)
    config: Path | None = None  # config folder, so errors can name a module file (S21)

    def modules_used(self) -> list[str]:
        if self.text is None:
            return ["shellrc"]
        return sorted({key.split(".")[0] for key in PLACEHOLDER.findall(self.text)})

    def _module_file(self, module: str) -> Path | None:
        return self.config / "modules" / f"{module}.toml" if self.config else None

    def render(self, modules: dict[str, dict]) -> str:
        if self.text is None:
            if "shellrc" not in modules:
                raise ConfigError(f"template {self.name}: missing module shellrc (add modules/shellrc.toml)",
                                  self._module_file("shellrc"))
            return _shell(self.name, modules["shellrc"])
        out = []
        for number, line in enumerate(self.text.splitlines(keepends=True), start=1):
            def fill(match, number=number):
                key = match.group(1)
                try:
                    return str(get_value(modules, key))
                except KeyError:
                    module = key.split(".")[0]
                    raise ConfigError(
                        f"template {self.name} ({self.source}, line {number}): missing key {key}; "
                        f"set it in modules/{module}.toml",
                        # A user's template is the file to fix; a built-in one cannot be edited, so name the module.
                        self.source if self.source != "built-in" else self._module_file(module),
                    ) from None
            out.append(PLACEHOLDER.sub(fill, line))
        return "".join(out)


BUILT_IN = {
    "bash": Template("bash", "built-in", None),
    "zsh": Template("zsh", "built-in", None),
    "fish": Template("fish", "built-in", None),
    "alacritty": Template("alacritty", "built-in", ALACRITTY),
}


def find_template(config: Path, name: str) -> Template:
    user_file = config / "templates" / f"{name}.tmpl"
    if user_file.is_file():
        return Template(name, str(user_file), user_file.read_text(encoding="utf-8"), config)
    if name in BUILT_IN:
        return replace(BUILT_IN[name], config=config)
    raise ConfigError(f"template {name}: not built in, and {user_file} does not exist", user_file)
